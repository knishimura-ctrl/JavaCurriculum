package curriculum.g;

public class Employee {
	String employeeld;
	String name;
	
	public void setEmployeeld(String employeeld) {
		this.employeeld = employeeld;
	}
	public String getEmployeeld() {
		return employeeld;
	}
	public void setName(String name) {
		this.name = name;
	}
	public String getName() {
		return name;
	}
}
